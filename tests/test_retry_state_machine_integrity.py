"""Retry and turn consistency invariants, each exercised by its own probe.

The ledger validates the retry policy the run pinned, permitted attempt order,
and the number of provider-reaching turns in addition to attempt indices and
summary arithmetic.

The probes edit rows produced through the shipped runner, reader and resume path:

1. A genuine three-attempt rate-limited turn shortened to two attempts, with
   every index, count, tally, measurement and total adjusted to agree.
2. A fourth attempt appended beyond the manifest's pinned three-attempt policy,
   with the same adjustments.
3. A genuine ``[fault, fault, response]`` turn reordered to
   ``[response, fault, fault]`` and renumbered, which no retry loop can produce
   because a response ends the turn.
4. One complete provider turn removed from a two-turn episode, with the episode
   and coverage summaries adjusted to match what was left.

Every row edited below is generated by the shipped runner and Anthropic adapter/SDK
against an in-process fake transport. No helper here produces both the
expected and the actual value, and no socket is opened.
"""

