# -- 3. a response ends the turn, so nothing follows it ----------------------


def _reorder_response_first(rows: list[dict[str, Any]]) -> None:
    turn = _turn(rows[0])
    attempts = turn["attempts"]
    reordered = [attempts[2], attempts[0], attempts[1]]
    for position, attempt in enumerate(reordered, start=1):
        attempt["index"] = position
    turn["attempts"] = reordered
    _retally(rows[0])


def test_a_response_reordered_before_later_attempts_is_refused(
    tmp_path: Path,
) -> None:
    """A ``[fault, fault, response]`` sequence rewritten as
    ``[response, fault, fault]`` and renumbered consecutively.

    Every summary survives the reordering untouched — the same three attempts,
    the same two faults, the same measured attempt, the same exposure — which is
    why arithmetic could not see it. The sequence is impossible all the same:
    the retry loop returns the moment a response arrives, so no attempt can
    follow one.
    """
    root = tmp_path / "run"
    rows = _answered_after_two_rate_limits(root)
    exposure = rows[0]["cost_exposure_usd"]
    _reorder_response_first(rows)
    assert rows[0]["cost_exposure_usd"] == exposure
    _write_rows(root, rows)

    with pytest.raises(LedgerError) as raised:
        _reread(root)

    assert "response" in str(raised.value)


def test_a_response_reordered_before_later_attempts_stops_the_resume(
    tmp_path: Path,
) -> None:
    root = tmp_path / "run"
    rows = _answered_after_two_rate_limits(root)
    _reorder_response_first(rows)
    _write_rows(root, rows)

    with pytest.raises(LedgerError):
        _resume(root)


def test_a_turn_that_ended_in_a_fault_may_not_be_followed_by_another_turn(
    tmp_path: Path,
) -> None:
    """The episode-level half of the same rule, on an uncapped provider run.

    A turn that ended in anything but a response ended the episode with it, so
    it is the last turn there is. Swapping a genuine response turn and a genuine
    exhausted-retry turn leaves every count and tally identical and is refused
    on the order alone.
    """
    root = tmp_path / "run"
    manifest = anthropic_manifest(retry=instant_retry())
    transport = RecordingTransport(
        [message_body([READ_RECORDS], model=PINNED_MODEL)] + [(429, error_body())] * 3,
        default=message_body([READ_RECORDS], model=PINNED_MODEL),
    )
    execute(root, manifest, anthropic_adapter(transport.client(), retry=instant_retry()))
    rows = ledger_rows(root)
    turns = rows[0]["provider_telemetry"]["turns"]
    assert [turn["terminal_reason"] for turn in turns] == [
        TURN_END_RESPONSE,
        TURN_END_RETRIES_EXHAUSTED,
    ]

    turns[0], turns[1] = turns[1], turns[0]
    turns[0]["turn_index"], turns[1]["turn_index"] = (
        turns[1]["turn_index"],
        turns[0]["turn_index"],
    )
    path = root / LEDGER_FILENAME
    path.write_text(
        "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows),
        encoding="utf-8",
    )

    with pytest.raises(LedgerError) as raised:
        read_ledger(path, manifest, variants())

    assert "response" in str(raised.value)


# -- 4. every provider-reaching turn of a capped run is accounted for --------


def _drop_the_second_turn(rows: list[dict[str, Any]]) -> None:
    telemetry = rows[0]["provider_telemetry"]
    telemetry["turns"] = telemetry["turns"][:1]
    _retally(rows[0])


def test_a_removed_provider_turn_is_refused(tmp_path: Path) -> None:
    """One of two provider turns deleted from the row.

    The episode still records the two turns it spent, and its trajectory still
    holds the two steps those turns produced; only the evidence of what the
    second turn asked of the provider is gone, with the episode tallies and the
    coverage summary adjusted to the partial measurement that leaves. A reader
    that only required turn indices to be sorted and unique had nothing to say
    about a turn that is simply absent.
    """
    root = tmp_path / "run"
    rows = _two_turn_row(root)
    _drop_the_second_turn(rows)
    assert rows[0]["measurement"]["status"] == MEASUREMENT_PARTIAL
    _write_rows(root, rows)

    with pytest.raises(LedgerError) as raised:
        _reread(root)

    assert "turn" in str(raised.value)


def test_a_removed_provider_turn_stops_the_resume(tmp_path: Path) -> None:
    root = tmp_path / "run"
    rows = _two_turn_row(root)
    _drop_the_second_turn(rows)
    _write_rows(root, rows)

    with pytest.raises(LedgerError):
        _resume(root)


def test_a_capped_row_whose_telemetry_is_null_is_refused(tmp_path: Path) -> None:
    """The same removal, taken to its end: every turn's evidence deleted."""
    root = tmp_path / "run"
