# -- the fixtures, asserted to be the evidence these probes claim to edit -----


def _turn(row: dict[str, Any], position: int = 0) -> dict[str, Any]:
    return row["provider_telemetry"]["turns"][position]


def _retally(row: dict[str, Any]) -> None:
    """Recompute every summary a coherent editor would recompute by hand.

    Deliberately *not* the production derivation: this is the attacker's side of
    each probe, making the edited row internally consistent. It recomputes only
    the totals — never the attempts or turns those totals summarise, which are
    what each probe edits.
    """
    telemetry = row["provider_telemetry"]
    turns = telemetry["turns"]
    for turn in turns:
        faults: dict[str, int] = {}
        for attempt in turn["attempts"]:
            if attempt["fault"] is not None:
                faults[attempt["fault"]] = faults.get(attempt["fault"], 0) + 1
        turn["attempt_count"] = len(turn["attempts"])
        turn["fault_counts"] = dict(sorted(faults.items()))
        turn["response_received"] = any(a["response_received"] for a in turn["attempts"])
        turn["usage_reported"] = any(a["usage_reported"] for a in turn["attempts"])
    episode_faults: dict[str, int] = {}
    for turn in turns:
        for fault, number in turn["fault_counts"].items():
            episode_faults[fault] = episode_faults.get(fault, 0) + number
    attempts = [attempt for turn in turns for attempt in turn["attempts"]]
    measured_turns = sum(1 for turn in turns if turn["turn_latency_seconds"] is not None)
    telemetry["attempt_count"] = len(attempts)
    telemetry["fault_counts"] = dict(sorted(episode_faults.items()))
    turns_used = row["turns_used"]
    status = (
        "unmeasured"
        if measured_turns == 0
        else ("full" if measured_turns == turns_used else MEASUREMENT_PARTIAL)
    )
    telemetry["measurement_status"] = status
    row["measurement"] = {
        "turns_total": turns_used,
        "turns_measured": measured_turns,
        "attempts_total": len(attempts),
        "attempts_measured": sum(
            1 for attempt in attempts if attempt["latency_seconds"] is not None
        ),
        "status": status,
    }
    row["cost_exposure_usd"] = float(
        sum(
            Decimal(attempt["cost_reservation_usd"])
            for attempt in attempts
            if attempt["cost_settlement"] == "forfeited"
        )
    )


def _answered_after_two_rate_limits(root: Path) -> list[dict[str, Any]]:
    """One real turn of ``[fault, fault, response]``, written by the real adapter."""
    capped_run(root, cap="100", steps=[RATE_LIMITED, RATE_LIMITED])
    rows = _rows(root)
    assert rows[0]["outcome"] == OUTCOME_SUCCESS
    outcomes = [attempt["outcome"] for attempt in _turn(rows[0])["attempts"]]
    assert outcomes == ["fault", "fault", "response"]
    return rows


def _two_turn_row(root: Path) -> list[dict[str, Any]]:
    """One real two-turn episode: the model reads, then completes the case."""
    capped_run(root, cap="100", steps=[message_body([READ_RECORDS], model=SONNET)])
    rows = _rows(root)
    assert rows[0]["turns_used"] == 2
    assert len(rows[0]["provider_telemetry"]["turns"]) == 2
    return rows


def test_the_rate_limited_fixture_is_a_genuine_three_attempt_turn(
    tmp_path: Path,
) -> None:
    """A negative probe against a row of the wrong shape would prove nothing."""
    rows = _rate_limited_row(tmp_path / "run")
    turn = _turn(rows[0])

    assert rows[0]["outcome"] == OUTCOME_PROVIDER_RATE_LIMITED
    assert turn["attempt_count"] == 3
    assert [attempt["index"] for attempt in turn["attempts"]] == [1, 2, 3]
    assert turn["terminal_reason"] == TURN_END_RETRIES_EXHAUSTED


def test_every_recorded_turn_states_a_reason_it_ended(tmp_path: Path) -> None:
    """The one field this fix adds, on real rows, from the closed set."""
    rows = _answered_after_two_rate_limits(tmp_path / "run")
    reasons = [
        turn["terminal_reason"]
        for row in rows
        for turn in row["provider_telemetry"]["turns"]
    ]

    assert reasons
    assert set(reasons) == {TURN_END_RESPONSE}
    for reason in reasons:
        assert reason in TURN_TERMINAL_REASONS


# -- 1. a turn may not record fewer attempts than the retries it ran ---------


def _shorten_to_two_attempts(rows: list[dict[str, Any]]) -> None:
    turn = _turn(rows[0])
    turn["attempts"] = turn["attempts"][:2]
    _retally(rows[0])


def test_a_three_attempt_turn_shortened_to_two_is_refused(tmp_path: Path) -> None:
    """A genuine three-failure turn edited to contain only two attempts.

    Every index, per-turn count, fault tally, episode tally, coverage summary
    and exposure total was adjusted to agree with the two attempts that were
    left, so the row followed from its own evidence — and a third of the run's
    real exposure had been dropped from the accounting. Nothing checked the
    attempts against the retry policy the manifest pins, or against the reason
    the turn recorded for stopping.
    """
    root = tmp_path / "run"
    rows = _rate_limited_row(root)
    reserved = first_request_reservation()
    assert rows[0]["cost_exposure_usd"] == float(reserved * 3)
    _shorten_to_two_attempts(rows)
    assert rows[0]["cost_exposure_usd"] == float(reserved * 2)
    _write_rows(root, rows)

    with pytest.raises(LedgerError) as raised:
        _reread(root)

    assert "terminal_reason" in str(raised.value)


def test_a_three_attempt_turn_shortened_to_two_stops_the_resume(
    tmp_path: Path,
) -> None:
    """The same forgery through the production resume path, which spent again."""
    root = tmp_path / "run"
    rows = _rate_limited_row(root)
    _shorten_to_two_attempts(rows)
    _write_rows(root, rows)

    with pytest.raises(LedgerError):
        _resume(root)


# -- 2. a turn may not record more attempts than the policy permits ----------


def test_a_fourth_attempt_beyond_the_pinned_policy_is_refused(tmp_path: Path) -> None:
    """A fourth attempt appended under a pinned ``max_attempts`` of three.

    The appended attempt is a copy of a real one — same rederived reservation,
    same fault, same status — renumbered 4, with every summary and the exposure
    total adjusted. The run's own adapter could not have made it: the retry
    policy is inside adapter settings and therefore inside run identity, and it
    stops at three.
    """
    root = tmp_path / "run"
    rows = _rate_limited_row(root)
    turn = _turn(rows[0])
    fourth = json.loads(json.dumps(turn["attempts"][2]))
    fourth["index"] = 4
    turn["attempts"].append(fourth)
    _retally(rows[0])
    assert rows[0]["cost_exposure_usd"] == float(first_request_reservation() * 4)
    _write_rows(root, rows)

    with pytest.raises(LedgerError) as raised:
        _reread(root)

    assert "max_attempts" in str(raised.value)


