def test_a_fake_adapter_run_records_no_provider_telemetry_and_reads_back(
    tmp_path: Path,
) -> None:
    """The unmeasured semantics this fix must leave exactly alone.

    An in-process fake reaches no provider, so it reports no attempts, no turns
    and no reason any turn ended. ``null`` telemetry is that claim, and the
    exact per-turn accounting a real capped provider run is held to has nothing
    to account for here.
    """
    root = tmp_path / "run"
    identity = fake_identity()
    manifest = build_manifest(
        provider=identity.provider,
        model=identity.model,
        implementation=identity.implementation,
        adapter_version=identity.version,
        adapter_settings={},
    )
    execute(root, manifest, PolicyFollowingFakeAdapter(settings={}))
    rows = ledger_rows(root)

    assert rows
    for row in rows:
        assert row["provider_telemetry"] is None
        assert row["measurement"]["status"] == "unmeasured"
    assert len(read_ledger(root / LEDGER_FILENAME, manifest, variants())) == len(rows)


