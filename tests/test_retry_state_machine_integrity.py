def test_an_unclassifiable_attempt_ends_the_turn_it_was_made_in(
    tmp_path: Path,
) -> None:
    """An attempt whose answer this build cannot name is terminal, like a response.

    The request was made and may have been billed, so it is recorded rather than
    dropped — but naming a provider fault nobody observed would be a fabricated
    diagnosis, and there is nothing left to retry against. A row that records one
    and then claims its retry policy ran out is refused: exhaustion is a claim
    about three attempts that each met a retryable fault.
    """
    root = tmp_path / "run"
    rows = _rate_limited_row(root)
    last = _turn(rows[0])["attempts"][-1]
    last["outcome"] = "unclassified_error"
    last["fault"] = None
    last["http_status"] = None
    _retally(rows[0])
    _write_rows(root, rows)

    with pytest.raises(LedgerError) as raised:
        _reread(root)

    assert TURN_END_UNCLASSIFIED in str(raised.value)


